/** 8 rows of 5 bits per glyph. */
export const FONT: Record<string, number[]> = Object.fromEntries(
  Object.entries(G).map(([ch, s]) => {
    const rows = s.split("|").map((r) => [...r].reduce((a, c) => (a << 1) | (c === "#" ? 1 : 0), 0));
    while (rows.length < 8) rows.push(0);
    return [ch, rows];
  }),
);
export const glyph = (ch: string): number[] => FONT[ch] ?? FONT["?"]!;
