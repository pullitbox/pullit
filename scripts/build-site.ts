// Builds worker/site.ts from worker/site.html + assets/box.svg (the Worker serves one string).
//   npm run site
import { readFileSync, writeFileSync } from "node:fs";

const svg = readFileSync("assets/box.svg", "utf8").trim();
const html = readFileSync("worker/site.html", "utf8").replaceAll("BOXSVG_URI", encodeURIComponent(svg));
writeFileSync(
  "worker/site.ts",
  `// generated by scripts/build-site.ts from worker/site.html, do not edit\nexport const HTML = ${JSON.stringify(html)};\n`,
);
const soon = readFileSync("worker/soon.html", "utf8").replaceAll("BOXSVG_URI", encodeURIComponent(svg));
writeFileSync(
  "worker/site.ts",
  `// generated by scripts/build-site.ts from worker/site.html and worker/soon.html, do not edit\nexport const HTML = ${JSON.stringify(html)};\nexport const SOON = ${JSON.stringify(soon)};\n`,
);
console.log(`worker/site.ts written (${(html.length / 1024).toFixed(1)} kB)`);
